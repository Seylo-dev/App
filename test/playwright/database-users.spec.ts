// The Users tab of a database: its users as the engine lists them, the main
// user first; the Connection tab's Change links landing on the main user's
// name or password dialog; a new user whose password shows once; a delete
// that gives a Postgres owner's tables to the main user first; a password
// change that names the services to redeploy and a MySQL root left behind;
// Redis with its one user; a MongoDB switch of the main user. Demo data
// (demo/service.ts usersOf) stands in for the engines; changes are
// answered here.
//
// Screenshots: $SHOTS_DIR/database-users/*.png.

import { mkdirSync } from "node:fs";
import { ids } from "./demo/fixtures";
import { installDemo } from "./demo/routes";
import { ids as svc, usersOf } from "./demo/service";
import { expect, stateFile, test } from "./helpers";

const shots = `${process.env.SHOTS_DIR ?? "shots"}/database-users`;
const tab = (serviceId: string, path: string) => `/p/${ids.acme}/s/${serviceId}/${path}`;

test.describe("database users", () => {
  test.use({ storageState: stateFile });
  test.beforeAll(() => mkdirSync(shots, { recursive: true }));

  test("the tab lists the users, main first, with a skeleton while they load", async ({ page }) => {
    await installDemo(page, { delay: (op) => (op === "databases.users" ? 600 : 0) });
    await page.goto(tab(svc.db, "users"));
    await expect(page.locator('main [data-slot="skeleton"]').first()).toBeVisible();
    const users = page.getByRole("region", { name: "Users" });
    await expect(users.getByRole("list", { name: "Users" }).getByRole("listitem")).toHaveCount(3);
    await expect(page.locator('main [data-slot="skeleton"]')).toHaveCount(0);
    await expect(page.getByRole("link", { name: "Users", exact: true })).toBeVisible();
    const rows = users.getByRole("listitem");
    await expect(rows.first()).toContainText("postgres");
    await expect(rows.first()).toContainText("Main");
    await expect(rows.first()).toContainText("Seylo signs in with this one");
    await expect(rows.nth(1)).toContainText("Read and write · owns 12 objects");
    await expect(rows.nth(2)).toContainText("Read only");
    // The main user has its two buttons, the others a menu.
    await expect(rows.first().getByRole("button", { name: "Change password" })).toBeVisible();
    await expect(rows.first().getByRole("button", { name: "Change name" })).toBeVisible();
    await rows.nth(2).getByRole("button", { name: "More actions for metabase" }).click();
    for (const item of ["Change password", "Rename", "Make this the main user", "Delete"]) await expect(page.getByRole("menuitem", { name: item })).toBeVisible();
    await page.keyboard.press("Escape");
    await page.screenshot({ path: `${shots}/postgres.png`, fullPage: true });
  });

  test("Change next to the password lands on the main user's password; the result names the services to redeploy", async ({ page }) => {
    let set: Record<string, unknown> | null = null;
    const warning =
      "The password of shop changed, but MySQL's root user kept an older password, which the panel does not know: root no longer signs in with the one the database's container gives it (MYSQL_ROOT_PASSWORD).";
    await installDemo(page, {
      overrides: {
        "databases.setUserPassword": (input) => {
          set = input;
          return { password: "Nw7pQ2xVb9Lk4Rt6", affectedServiceIds: [svc.web], deploymentId: null, warning };
        },
      },
    });
    await page.goto(tab(svc.db, "connection"));
    await page.getByRole("region", { name: "Internal connection" }).getByRole("link", { name: "Change the password" }).click();
    await expect(page).toHaveURL(tab(svc.db, "users"));
    const confirm = page.getByRole("alertdialog");
    await expect(confirm.getByRole("heading", { name: "Change the main user's password?" })).toBeVisible();
    await expect(confirm).toContainText("postgres is the user Seylo and your services sign in with");
    const submit = confirm.getByRole("button", { name: "Change password" });
    await expect(submit).toBeDisabled();
    await confirm.getByRole("textbox").fill("db");
    await submit.click();
    await expect.poll(() => set).not.toBeNull();
    // Generated by the panel: no password in the call.
    expect(set).toEqual({ serviceId: svc.db, user: { name: "postgres" } });
    const done = page.getByRole("dialog");
    await expect(done.getByRole("heading", { name: "New password for postgres" })).toBeVisible();
    await expect(done).toContainText("1 service references this database");
    await expect(done.getByRole("listitem")).toContainText("web");
    await expect(done.getByRole("link", { name: "Redeploy" })).toHaveAttribute("href", tab(svc.web, "deployments"));
    await expect(done.getByRole("note")).toHaveText(warning);
    await page.waitForTimeout(400);
    await page.screenshot({ path: `${shots}/main-password.png` });
  });

  test("Change next to the user opens the rename of the main user, with its restart", async ({ page }) => {
    let renamed: Record<string, unknown> | null = null;
    await installDemo(page, {
      overrides: {
        "databases.renameUser": (input) => {
          renamed = input;
          return { user: { name: String(input.name) }, password: null, affectedServiceIds: [], deploymentId: "d000000000000009", warning: null };
        },
      },
    });
    await page.goto(tab(svc.db, "connection"));
    await page.getByRole("region", { name: "Exposed connection" }).getByRole("link", { name: "Change the user" }).click();
    const confirm = page.getByRole("alertdialog");
    await expect(confirm.getByRole("heading", { name: "Rename the main user?" })).toBeVisible();
    await confirm.getByRole("textbox", { name: "New name" }).fill("shop_owner");
    await expect(confirm.getByLabel("Restart the database now, so its health check uses the new name (a short outage).")).toBeChecked();
    await confirm.getByLabel("Type db to confirm").fill("db");
    await confirm.getByRole("button", { name: "Rename" }).click();
    await expect.poll(() => renamed).not.toBeNull();
    expect(renamed).toEqual({ serviceId: svc.db, user: { name: "postgres" }, name: "shop_owner" });
    const done = page.getByRole("dialog");
    await expect(done.getByRole("heading", { name: "The main user is now shop_owner" })).toBeVisible();
    await expect(done).toContainText("The database restarts with it now.");
    await expect(done).toContainText("No service of this project references it.");
  });

  test("a new user's password shows once, with its URLs", async ({ page }) => {
    let created: Record<string, unknown> | null = null;
    await installDemo(page, {
      overrides: {
        "databases.createUser": (input) => {
          created = input;
          const password = "Gq4mT8vXn2Lp7Rw3Kb9Hs6Dc1Fz5Yj0A";
          return {
            user: { ...usersOf(svc.db).users[2], name: String(input.name), access: input.access },
            password,
            internalUrl: `postgresql://${input.name}:${password}@db:5432/shop`,
            exposedUrl: `postgresql://${input.name}:${password}@203.0.113.10:15432/shop?sslmode=require`,
          };
        },
      },
    });
    await page.goto(tab(svc.db, "users"));
    await page.getByRole("button", { name: "New user" }).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog.getByRole("heading", { name: "New user" })).toBeVisible();
    await dialog.getByLabel("Name").fill("reports");
    await dialog.getByRole("combobox", { name: "Access" }).click();
    await expect(page.getByRole("option")).toHaveText(["Read only", "Read and write", "Full admin"]);
    await page.getByRole("option", { name: "Read only" }).click();
    await expect(dialog).toContainText("in every database of this server (pg_read_all_data)");
    await page.screenshot({ path: `${shots}/new-user.png` });
    await dialog.getByRole("button", { name: "Create user" }).click();
    await expect.poll(() => created).not.toBeNull();
    expect(created).toEqual({ serviceId: svc.db, name: "reports", access: "readOnly" });
    await expect(dialog.getByRole("heading", { name: "reports is ready" })).toBeVisible();
    await expect(dialog).toContainText("Seylo does not keep it");
    await expect(dialog.getByText("Gq4mT8vXn2Lp7Rw3Kb9Hs6Dc1Fz5Yj0A", { exact: true })).toBeVisible();
    await expect(dialog.getByLabel("Exposed connection URL")).toBeVisible();
    await page.screenshot({ path: `${shots}/new-user-done.png` });
  });

  test("deleting an owner gives its tables to the main user first; a set own password must fit", async ({ page }) => {
    let deleted: Record<string, unknown> | null = null;
    await installDemo(page, {
      overrides: {
        "databases.deleteUser": (input) => {
          deleted = input;
          return { deleted: true, reassignedObjects: 12 };
        },
      },
    });
    await page.goto(tab(svc.db, "users"));
    const app = page.getByRole("listitem").filter({ hasText: "shop_app" });
    await app.getByRole("button", { name: "More actions for shop_app" }).click();
    await page.getByRole("menuitem", { name: "Delete" }).click();
    const confirm = page.getByRole("alertdialog");
    await expect(confirm.getByRole("heading", { name: "Delete shop_app?" })).toBeVisible();
    const submit = confirm.getByRole("button", { name: "Delete" });
    await expect(submit).toBeDisabled();
    await confirm.getByLabel(/Give its 12 tables and other objects to postgres first/).check();
    await submit.click();
    await expect.poll(() => deleted).not.toBeNull();
    expect(deleted).toEqual({ serviceId: svc.db, user: { name: "shop_app" }, reassignOwned: true });
    await expect(page.getByText("shop_app is deleted.")).toBeVisible();

    await page.getByRole("listitem").filter({ hasText: "metabase" }).getByRole("button", { name: "More actions for metabase" }).click();
    await page.getByRole("menuitem", { name: "Change password" }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("radio", { name: "Set my own" }).click();
    await dialog.getByRole("textbox", { name: "Password" }).fill("short");
    await expect(dialog.getByRole("button", { name: "Change password" })).toBeDisabled();
    await dialog.getByRole("textbox", { name: "Password" }).fill("LongEnoughPassword1");
    await expect(dialog.getByRole("button", { name: "Change password" })).toBeEnabled();
  });

  test("a stopped database says why and opens no dialog from a Change link", async ({ page }) => {
    const message = "The database is stopped. Start it to see and change its users.";
    const stopped = usersOf(svc.db);
    await installDemo(page, {
      overrides: {
        "databases.users": () => ({
          ...stopped,
          signIn: "offline",
          message,
          users: [{ ...stopped.users[0], can: { passwordChange: false, rename: false, delete: false, makeMain: false }, why: message }],
        }),
      },
    });
    for (const change of ["password", "name"]) {
      await page.goto(`${tab(svc.db, "users")}?change=${change}`);
      await expect(page.getByRole("note").filter({ hasText: message })).toBeVisible();
      await expect(page).toHaveURL(tab(svc.db, "users"));
      await expect(page.getByRole("alertdialog")).toHaveCount(0);
    }
    await expect(page.getByRole("button", { name: "New user" })).toHaveCount(0);
  });

  test("Redis has its one default user and says why", async ({ page }) => {
    await installDemo(page);
    await page.goto(tab(svc.redis, "connection"));
    const internal = page.getByRole("region", { name: "Internal connection" });
    await expect(internal.getByRole("link", { name: "Change the password" })).toBeVisible();
    await expect(internal.getByRole("link", { name: "Change the user" })).toHaveCount(0);
    await page.goto(tab(svc.redis, "users"));
    const users = page.getByRole("region", { name: "Users" });
    await expect(users.getByRole("listitem")).toHaveCount(1);
    await expect(users).toContainText("default");
    await expect(users.getByRole("note")).toContainText("ACL SETUSER live in memory only");
    await expect(users.getByRole("button", { name: "New user" })).toHaveCount(0);
    await expect(users.getByRole("button", { name: "Change name" })).toHaveCount(0);
    await expect(users.getByRole("button", { name: "Change password" })).toBeVisible();
    await page.screenshot({ path: `${shots}/redis.png`, fullPage: true });
  });

  test("MongoDB's main user changes name by a switch to a new user", async ({ page }) => {
    let switched: Record<string, unknown> | null = null;
    const mongo = {
      ...usersOf(svc.db),
      engine: "mongo",
      presets: ["readOnly", "readWrite", "databaseAdmin", "serverAdmin"],
      main: { user: "root", rename: "switch", canSwitch: true },
      users: [
        { ...usersOf(svc.db).users[0], name: "root", authDatabase: "admin", roles: ["root@admin"] },
        { ...usersOf(svc.db).users[2], name: "analytics", authDatabase: "admin", roles: ["read@shop"], passwordForRename: true },
      ],
    };
    await installDemo(page, {
      overrides: {
        "databases.users": () => mongo,
        "databases.switchMainUser": (input) => {
          switched = input;
          return { user: String(input.name), password: "Mn4bV8cXz2Lk7Jh3Gf9Ds6Aq1Wp5Ey0R", affectedServiceIds: [svc.api, svc.worker], deploymentId: null, warning: null };
        },
      },
    });
    await page.goto(`${tab(svc.db, "users")}?change=name`);
    const confirm = page.getByRole("alertdialog");
    await expect(confirm.getByRole("heading", { name: "Use another user as the main one" })).toBeVisible();
    // The deep link is used once: a reload does not open it again.
    await expect(page).toHaveURL(tab(svc.db, "users"));
    await confirm.getByLabel("Name").fill("boss");
    await confirm.getByLabel(/The old main user, root/).check();
    await confirm.getByLabel("Type db to confirm").fill("db");
    await confirm.getByRole("button", { name: "Switch" }).click();
    await expect.poll(() => switched).not.toBeNull();
    expect(switched).toEqual({ serviceId: svc.db, name: "boss", oldUser: "delete" });
    const done = page.getByRole("dialog");
    await expect(done.getByRole("heading", { name: "New password for boss" })).toBeVisible();
    await expect(done).toContainText("2 services reference this database");
    await expect(done.getByRole("link", { name: "Redeploy" })).toHaveCount(2);
    await page.waitForTimeout(400);
    await page.screenshot({ path: `${shots}/mongo-switch.png` });
  });
});
