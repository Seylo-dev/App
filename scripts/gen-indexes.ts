// Writes the index files that list every op module and every panel module.
// Generating them means a new feature adds its own files and never edits a
// shared list, so parallel changes do not conflict.
//
//   packages/ops/src/ops/*.ts            -> packages/ops/src/ops/index.gen.ts
//   apps/panel/src/modules/*/index.ts    -> apps/panel/src/modules/index.gen.ts
//   apps/web/src/i18n/en/*.ts            -> apps/web/src/i18n/en/index.gen.ts
//
// Run through `make gen`; scripts/check-generated.sh fails when they are stale.

import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const header = "// Code generated by scripts/gen-indexes.ts. DO NOT EDIT.\n";
const identifier = /^[a-z][a-zA-Z0-9]*$/;

function checkName(name: string, where: string): string {
  if (!identifier.test(name)) {
    throw new Error(`${where}: "${name}" must be lower camel case so it can be an identifier and an op id prefix`);
  }
  return name;
}

/** Names of the .ts files in a folder, without generated files and tests. */
function sourceFiles(relativeDir: string): string[] {
  return readdirSync(join(root, relativeDir))
    .filter((file) => file.endsWith(".ts") && !file.endsWith(".gen.ts") && !file.endsWith(".test.ts"))
    .map((file) => checkName(file.slice(0, -3), relativeDir))
    .sort();
}

function opModules(): string {
  const names = sourceFiles("packages/ops/src/ops");
  return [
    header,
    ...names.map((name) => `import * as ${name} from "./${name}";`),
    "",
    `export { ${names.join(", ")} };`,
    "",
    "/** Every op module by name; the name is the id prefix of its ops. */",
    `export const opModules = { ${names.join(", ")} } as const;`,
    "",
  ].join("\n");
}

function panelModules(): string {
  const dir = join(root, "apps/panel/src/modules");
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, "index.ts")))
    .map((entry) => checkName(entry.name, "apps/panel/src/modules"))
    .sort();
  return [
    header,
    ...names.map((name) => `import ${name} from "./${name}";`),
    "",
    "/** Every panel feature module; each one's default export is a defineModule() result. */",
    `export const modules = [${names.join(", ")}] as const;`,
    "",
  ].join("\n");
}

function englishCatalog(): string {
  const names = sourceFiles("apps/web/src/i18n/en");
  return [
    header,
    ...names.map((name) => `import ${name} from "./${name}";`),
    "",
    "/** The English catalog: one section per file in this folder, keyed by file name. */",
    `export const en = { ${names.join(", ")} } as const;`,
    "",
  ].join("\n");
}

writeFileSync(join(root, "packages/ops/src/ops/index.gen.ts"), opModules());
writeFileSync(join(root, "apps/panel/src/modules/index.gen.ts"), panelModules());
writeFileSync(join(root, "apps/web/src/i18n/en/index.gen.ts"), englishCatalog());
