#!/usr/bin/env bash
# Writes packages/proto/src/gen/index.ts, re-exporting every file protoc-gen-es
# produced, so adding a .proto file never needs a hand-edited barrel.
set -euo pipefail

gen_dir="$(cd "$(dirname "$0")/.." && pwd)/packages/proto/src/gen"
index="$gen_dir/index.ts"

{
  echo "// Code generated by scripts/gen-proto-index.sh. DO NOT EDIT."
  echo
  (cd "$gen_dir" && find . -name '*_pb.ts' | LC_ALL=C sort) | while read -r file; do
    echo "export * from \"${file%.ts}\";"
  done
} >"$index"
