// No lookup: each reason is said once, and the check still reads the
// servers. Docker out of reach runs no container.
func TestContainerDNSLookupSkipped(t *testing.T) {
	timedOut := context.DeadlineExceeded
	for _, tc := range []struct {
		name   string
		node   dnsNode
		live   *bool
		detail string
		ran    bool
	}{
		{name: "no edge network yet", node: dnsNode{images: "alpine:3.20\n", resolv: hostResolvConf, noEdge: true}, live: ptr(true),
			detail: "; no lookup from a test container: there is no seylo-edge network yet (the agent creates it when it starts)"},
		{name: "no image", node: dnsNode{images: "node:22\n"}, live: ptr(true), detail: "and the check pulls none)"},
		{name: "no nslookup in the image", node: dnsNode{images: "alpine:3.20\n", resolv: hostResolvConf,
			lookup: lookupOut("1.00", "1.00", 127, "sh: 1: nslookup: not found\n", lookupResolvConf)}, live: ptr(true),
			detail: "; no lookup from a test container: alpine:3.20 has no nslookup", ran: true},
		{name: "Docker does not answer in time", node: dnsNode{images: "alpine:3.20\n", resolv: hostResolvConf, lookupErr: timedOut}, live: ptr(true),
			detail: "; no lookup from a test container: the test container from alpine:3.20 did not run on seylo-edge: context deadline exceeded", ran: true},
		{name: "Docker is not reachable", node: dnsNode{}, detail: "no lookup from a test container: Docker is not reachable (no docker)"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			r, node, _ := runDNS(t, dnsCase{daemonJSON: "{}", dockerd: "/usr/bin/dockerd -H fd://", node: tc.node, live: tc.live})
			t.Logf("%v | %s", r.GetStatus(), r.GetDetail())
			if r.GetStatus() != agentv1.NodeCheckStatus_NODE_CHECK_STATUS_PASS || !strings.Contains(r.GetDetail(), tc.detail) {
				t.Fatalf("%v %q, want a pass with %q", r.GetStatus(), r.GetDetail(), tc.detail)
			}
			if strings.Count(r.GetDetail(), "no lookup") > 1 || strings.Contains(r.GetDetail(), "either") {
				t.Errorf("the reason twice: %q", r.GetDetail())
			}
			var ran bool
			for i, c := range node.cmds {
				if strings.Contains(c, " --entrypoint sh ") {
					ran = true
					// A run that failed removes its container.
					if tc.node.lookupErr != nil && (i+1 >= len(node.cmds) || !strings.Contains(node.cmds[i+1], "docker rm -f seylo-dnscheck-")) {
						t.Errorf("no docker rm -f after the failed lookup: %q", node.cmds)
					}
				}
			}
			if ran != tc.ran {
				t.Errorf("lookup ran %v, want %v: %q", ran, tc.ran, node.cmds)
			}
		})
	}
}

// The lookup and its container's whole run are bounded, and a run cut off
// by the bound is reported as no lookup and removed with a live context.
func TestLookupBound(t *testing.T) {
	if lookupWait >= lookupTimeout || !strings.Contains(lookupScript, fmt.Sprintf("-timeout=%d ", int(lookupWait/time.Second))) {
		t.Fatalf("nslookup's limit %v within the run's %v: %s", lookupWait, lookupTimeout, lookupScript)
	}
	env, node, _ := dnsEnv(t, dnsCase{node: dnsNode{images: "alpine:3.20\n", lookupErr: context.DeadlineExceeded}, live: ptr(true)})
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	l := env.lookupDNS(ctx, "alpine:3.20", nil)
	if l.Skipped != "no lookup from a test container: Docker did not run it within 20s" {
		t.Fatalf("lookup cut off = %+v", l)
	}
	if last := node.cmds[len(node.cmds)-1]; !strings.Contains(last, " docker rm -f seylo-dnscheck-") {
		t.Fatalf("no docker rm -f after the cut-off run: %q", node.cmds)
	}
	if len(node.deadRm) > 0 {
		t.Fatalf("removed with a context already done: %q", node.deadRm)
	}
}

// Docker out of reach: no container, and the reason.
func TestLookupWithoutDocker(t *testing.T) {
	env, node, _ := dnsEnv(t, dnsCase{node: dnsNode{images: "alpine:3.20\n"}, live: ptr(true)})
	l := env.lookupDNS(context.Background(), "alpine:3.20", errors.New("dial unix /var/run/docker.sock: connect: no such file or directory"))
	if l.Skipped != "no lookup from a test container: Docker is not reachable (dial unix /var/run/docker.sock: connect: no such file or directory)" || len(node.cmds) > 0 {
		t.Fatalf("lookup = %+v, commands %q", l, node.cmds)
	}
}
