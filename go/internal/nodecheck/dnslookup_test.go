// The lookup container's output, as the test VM's Docker 29.5 printed it
// (busybox 1.37 and alpine 3.22's busybox; traefik and moby/buildkit print
// the same), with its resolv.conf on a user-defined network.
const lookupResolvConf = `# Generated by Docker Engine.
# This file can be edited; Docker Engine will not make further changes once it
# has been modified.

nameserver 127.0.0.11
options timeout:1 attempts:2 ndots:0

# Based on host file: '/etc/resolv.conf' (internal resolver)
# ExtServers: [host(1.1.1.1) host(192.168.5.3)]
# Overrides: []
# Option ndots from: internal
`

// lookupOut is lookupScript's output: nslookup's lines between the two
// uptimes, its exit status, then resolv.conf.
func lookupOut(start, end string, exit int, nslookup, resolv string) string {
	return "@start " + start + "\n" + nslookup + fmt.Sprintf("@exit %d\n@end %s\n@resolv.conf\n", exit, end) + resolv
}

const answer = "Server:\t\t127.0.0.11\nAddress:\t127.0.0.11:53\n\nNon-authoritative answer:\nName:\tgithub.com\nAddress: 20.217.135.5\n\n"

// lookupWorks is a fast answer (30 ms).
var lookupWorks = lookupOut("298230.41", "298230.44", 0, answer, lookupResolvConf)

// lookupDropped is the VM's lookup through a container whose only server
// (--dns 192.0.2.53) drops every query: nslookup gives up after its 5 s.
var lookupDropped = lookupOut("298238.62", "298243.63", 1,
	"Server:\t\t127.0.0.11\nAddress:\t127.0.0.11:53\n\n;; connection timed out; no servers could be reached\n\n",
	strings.ReplaceAll(strings.ReplaceAll(lookupResolvConf, "[host(1.1.1.1) host(192.168.5.3)]", "[192.0.2.53]"), "# Overrides: []", "# Overrides: [nameservers]"))

// lookupServfail is the embedded DNS answering at once that it has no
// server to ask (--dns 127.0.0.1 in the VM).
var lookupServfail = lookupOut("298514.73", "298514.73", 1,
	"Server:\t\t127.0.0.11\nAddress:\t127.0.0.11:53\n\n** server can't find github.com: SERVFAIL\n\n",
	strings.ReplaceAll(lookupResolvConf, "[host(1.1.1.1) host(192.168.5.3)]", "[127.0.0.1]"))

func TestParseLookupOutput(t *testing.T) {
	for _, tc := range []struct {
		name          string
		out           string
		took          time.Duration
		exit          int
		address, err  string
		ext           []string
		unreadable    bool
		noResolvConf  bool
		wantLineCount int
	}{
		{name: "an answer", out: lookupWorks, took: 30 * time.Millisecond, address: "20.217.135.5", ext: []string{"host(1.1.1.1)", "host(192.168.5.3)"}},
		{name: "dropped", out: lookupDropped, took: 5010 * time.Millisecond, exit: 1, err: "connection timed out; no servers could be reached", ext: []string{"192.0.2.53"}},
		{name: "SERVFAIL", out: lookupServfail, exit: 1, err: "server can't find github.com: SERVFAIL", ext: []string{"127.0.0.1"}},
		{name: "NXDOMAIN", out: lookupOut("298514.46", "298514.47", 1, "Server:\t\t127.0.0.11\nAddress:\t127.0.0.11:53\n\n** server can't find nonexistent.invalid: NXDOMAIN\n\n", lookupResolvConf),
			took: 10 * time.Millisecond, exit: 1, err: "server can't find nonexistent.invalid: NXDOMAIN", ext: []string{"host(1.1.1.1)", "host(192.168.5.3)"}},
		// busybox before 1.28 numbers its addresses and names them.
		{name: "old busybox", out: lookupOut("10.00", "10.12", 0, "Server:    127.0.0.11\nAddress 1: 127.0.0.11\n\nName:      github.com\nAddress 1: 140.82.121.4 lb-140-82-121-4-fra.github.com\n", ""),
			took: 120 * time.Millisecond, address: "140.82.121.4", noResolvConf: true},
		// No A record: busybox says so and still exits 0.
		{name: "no answer", out: lookupOut("1.00", "1.02", 0, "Server:\t\t127.0.0.11\nAddress:\t127.0.0.11:53\n\nNon-authoritative answer:\n*** Can't find example.invalid: No answer\n\n", lookupResolvConf),
			took: 20 * time.Millisecond, err: "Can't find example.invalid: No answer", ext: []string{"host(1.1.1.1)", "host(192.168.5.3)"}},
		{name: "cut off", out: "@start 1.00\nServer:\t\t127.0.0.11\n", unreadable: true},
		{name: "not our output", out: lookupResolvConf, unreadable: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			took, exit, lines, rc, ok := parseLookupOutput(tc.out)
			if ok == tc.unreadable {
				t.Fatalf("ok = %v", ok)
			}
			if tc.unreadable {
				return
			}
			address, errText := nslookupAnswer(lines)
			if took != tc.took || exit != tc.exit || address != tc.address || errText != tc.err {
				t.Fatalf("took %v exit %d address %q error %q, want %v %d %q %q", took, exit, address, errText, tc.took, tc.exit, tc.address, tc.err)
			}
			if tc.noResolvConf {
				if rc != nil && len(rc.Servers) > 0 {
					t.Fatalf("resolv.conf %+v", rc)
				}
				return
			}
			if rc == nil || !slices.Equal(rc.Servers, []string{embeddedDNS}) || !slices.Equal(rc.ExtServers, tc.ext) {
				t.Fatalf("resolv.conf %+v, want the embedded DNS forwarding to %q", rc, tc.ext)
			}
		})
	}
}

func TestLookupTime(t *testing.T) {
	for d, want := range map[time.Duration]string{0: "under 10 ms", 30 * time.Millisecond: "30 ms", 990 * time.Millisecond: "990 ms",
		time.Second: "1.0 s", 2450 * time.Millisecond: "2.5 s", 5010 * time.Millisecond: "5.0 s"} {
		if got := lookupTime(d); got != want {
			t.Errorf("lookupTime(%v) = %q, want %q", d, got, want)
		}
	}
}

// lookupCommand matches the lookup container's command: a named, labeled
// container on the edge network from an image already here, removed when
// it is done, resolving the first of ResolveNames.
var lookupCommand = regexp.MustCompile(`docker run --rm --name seylo-dnscheck-[0-9a-f]{8} --pull never --network seylo-edge --label seylo\.dnscheck=true --label traefik\.enable=false --entrypoint sh alpine:3\.20 -c read a b </proc/uptime; .*nslookup -type=a -timeout=5 "\$1" .* sh github\.com$`)

// A node whose daemon.json is fine (the incident's: "dns": ["8.8.8.8",
// "1.1.1.1"]): the check now also resolves a name from a test container
// on the edge network, and says whether it works, is slow or fails, next
// to what daemon.json says.
func TestContainerDNSLookup(t *testing.T) {
	const (
		pass = agentv1.NodeCheckStatus_NODE_CHECK_STATUS_PASS
		wrn  = agentv1.NodeCheckStatus_NODE_CHECK_STATUS_WARN
		fl   = agentv1.NodeCheckStatus_NODE_CHECK_STATUS_FAIL
	)
	incident := `{"dns": ["8.8.8.8", "1.1.1.1"], "live-restore": true}`
	ext := strings.ReplaceAll(lookupResolvConf, "[host(1.1.1.1) host(192.168.5.3)]", "[8.8.8.8 1.1.1.1]")
	ext = strings.ReplaceAll(ext, "# Overrides: []", "# Overrides: [nameservers]")
	setting := `from "dns": [8.8.8.8, 1.1.1.1] in `
	for _, tc := range []struct {
		name     string
		lookup   string
		want     agentv1.NodeCheckStatus
		detail   []string
		hint     []string
		noHint   []string
		hintless bool
	}{
		{
			name:     "works",
			lookup:   lookupOut("100.00", "100.02", 0, answer, ext),
			want:     pass,
			detail:   []string{setting, "; a test container on seylo-edge resolved github.com in 20 ms through Docker's embedded DNS, which forwards to 8.8.8.8, 1.1.1.1"},
			hintless: true,
		},
		{
			name:   "slow",
			lookup: lookupOut("100.00", "102.53", 0, answer, ext),
			want:   wrn,
			detail: []string{"a test container on seylo-edge resolved github.com through Docker's embedded DNS, which forwards to 8.8.8.8, 1.1.1.1, but slowly: in 2.5 s; a test container on Docker's default bridge", setting},
			hint: []string{"a slow one means 8.8.8.8, 1.1.1.1 answer late or drop some queries", "`dig @8.8.8.8 github.com`, a few times",
				`put them in %FILE% ("dns": [...]) and restart Docker`, "Live-restore is on"},
		},
		{
			name:   "fails: the servers do not answer from this node",
			lookup: lookupOut("100.00", "105.01", 1, "Server:\t\t127.0.0.11\nAddress:\t127.0.0.11:53\n\n;; connection timed out; no servers could be reached\n\n", ext),
			want:   fl,
			detail: []string{"a test container on seylo-edge could not resolve github.com through Docker's embedded DNS, which forwards to 8.8.8.8, 1.1.1.1: " +
				"connection timed out; no servers could be reached (after 5.0 s); a test container on Docker's default bridge (alpine:3.20) gets 8.8.8.8, 1.1.1.1, " + setting},
			hint: []string{"Check on the node that 8.8.8.8, 1.1.1.1 answer (`dig @8.8.8.8 github.com`)",
				"the node's firewall, or the hosting provider's", "`systemctl restart docker`", "Live-restore is on, so containers keep running through the restart"},
			// The setting itself is fine: no hint to put addresses in it or remove it.
			noHint: []string{"already gives", `remove its "dns" key`},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			r, node, etc := runDNS(t, dnsCase{
				daemonJSON: incident,
				dockerd:    "/usr/bin/dockerd -H fd://",
				node:       dnsNode{images: "alpine:3.20\n", resolv: overrideResolvConf("8.8.8.8", "1.1.1.1"), lookup: tc.lookup},
				live:       ptr(true),
			})
			t.Logf("%v\n  detail: %s\n  hint: %s", r.GetStatus(), r.GetDetail(), r.GetFixHint())
			if r.GetStatus() != tc.want {
				t.Fatalf("status %v, want %v", r.GetStatus(), tc.want)
			}
			file := filepath.Join(etc, "docker", "daemon.json")
			for _, want := range tc.detail {
				if !strings.Contains(r.GetDetail(), want) {
					t.Errorf("detail lacks %q", want)
				}
			}
			for _, want := range tc.hint {
				if want = strings.ReplaceAll(want, "%FILE%", file); !strings.Contains(r.GetFixHint(), want) {
					t.Errorf("hint lacks %q", want)
				}
			}
			for _, not := range tc.noHint {
				if strings.Contains(r.GetFixHint(), not) {
					t.Errorf("hint has %q", not)
				}
			}
			if tc.hintless && r.GetFixHint() != "" {
				t.Errorf("a hint for a check that passes: %q", r.GetFixHint())
			}
			var lookups int
			for _, c := range node.cmds {
				if strings.Contains(c, " --entrypoint sh ") {
					lookups++
					if !lookupCommand.MatchString(c) {
						t.Errorf("lookup command %q", c)
					}
				}
				if strings.Contains(c, "docker pull") || strings.Contains(c, "docker image pull") {
					t.Errorf("pulled: %q", c)
				}
			}
			if lookups != 1 {
				t.Errorf("%d lookups: %q", lookups, node.cmds)
			}
		})
	}
}

