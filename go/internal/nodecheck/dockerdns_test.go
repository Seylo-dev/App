// The host's dockerd, not a second one whose pid sorts first: a dind
// container's (another PID namespace) or another user's rootless one
// (another user namespace).
func TestDockerdArgs(t *testing.T) {
	host := map[string]string{
		"proc/987/comm":    "dockerd\n",
		"proc/987/cmdline": "/usr/bin/dockerd\x00-H\x00fd://\x00",
		// "10234" sorts before "987".
		"proc/10234/comm":    "dockerd\n",
		"proc/10234/cmdline": "dockerd\x00--dns\x00127.0.0.11\x00--config-file\x00/etc/dind.json\x00",
		"proc/1/comm":        "systemd\n",
		"proc/1/cmdline":     "/sbin/init\x00",
	}
	with := func(extra map[string]string) map[string]string {
		m := maps.Clone(host)
		maps.Copy(m, extra)
		return m
	}
	// ns gives this process the host's namespaces, plus the processes'.
	ns := func(procs map[string]string) map[string]string {
		m := map[string]string{"proc/self/ns/pid": "pid:[4026531836]", "proc/self/ns/user": "user:[4026531837]"}
		maps.Copy(m, procs)
		return m
	}
	for _, tc := range []struct {
		name  string
		files map[string]string
		links map[string]string
		node  dnsNode
		from  string
	}{
		{name: "the pid file", files: with(map[string]string{"run/docker.pid": "987\n"}), from: "dockerd's command line (pid 987)"},
		{name: "docker.service's MainPID", files: host, node: dnsNode{mainPID: "987\n"}, from: "dockerd's command line (pid 987)"},
		{name: "a stale pid file", files: with(map[string]string{"run/docker.pid": "1\n"}), node: dnsNode{mainPID: "0\n"}, from: "dockerd's command line (pid 987)"},
		{
			name:  "another PID namespace",
			files: host,
			links: ns(map[string]string{"proc/987/ns/pid": "pid:[4026531836]", "proc/987/ns/user": "user:[4026531837]", "proc/10234/ns/pid": "pid:[4026532901]", "proc/10234/ns/user": "user:[4026531837]"}),
			from:  "dockerd's command line (pid 987)",
		},
		{
			name:  "another user namespace (rootless), the other unreadable",
			files: host,
			links: ns(map[string]string{"proc/987/ns/pid": "pid:[4026531836]", "proc/987/ns/user": "user:[4026532777]"}),
			from:  "dockerd's command line (pid 10234)",
		},
		{
			name:  "one known to share both first",
			files: host,
			links: ns(map[string]string{"proc/10234/ns/pid": "pid:[4026531836]", "proc/10234/ns/user": "user:[4026531837]"}),
			from:  "dockerd's command line (pid 10234)",
		},
		{name: "nothing to tell them apart: the lowest pid", files: host, from: "dockerd's command line (pid 987)"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			env, _, _ := dnsEnv(t, dnsCase{files: tc.files, links: tc.links, node: tc.node})
			args, from := env.dockerdArgs(context.Background())
			if from != tc.from {
				t.Fatalf("from %q, want %q (args %q)", from, tc.from, args)
			}
		})
	}
	// The dind's --dns is not reported as the host's setting.
	r, _, _ := runDNS(t, dnsCase{files: with(map[string]string{"run/docker.pid": "987\n"}), node: dnsNode{images: "alpine:3.20\n", resolv: hostResolvConf}, live: ptr(true)})
	if r.GetStatus() != agentv1.NodeCheckStatus_NODE_CHECK_STATUS_PASS || strings.Contains(r.GetDetail(), "127.0.0.11") {
		t.Fatalf("with a dind dockerd: %v %q", r.GetStatus(), r.GetDetail())
	}
}

// A test container a cut-off run left behind is removed by the next run
// (once older than any run), and a run that fails removes its own.
func TestProbeLeftovers(t *testing.T) {
	now := time.Now()
	leftover := func(id string, age time.Duration, labels map[string]string) DockerContainer {
		return DockerContainer{ID: id, Names: []string{"/seylo-dnscheck-" + id}, State: "created", Created: now.Add(-age).Unix(), Labels: labels}
	}
	ours := map[string]string{docker.LabelDNSCheck: "true", docker.LabelTraefikEnable: "false"}
	env, node, _ := dnsEnv(t, dnsCase{node: dnsNode{images: "alpine:3.20\n", resolv: hostResolvConf}, live: ptr(true),
		others: []DockerContainer{leftover("old1", time.Hour, ours), leftover("old2", 3*time.Minute, ours), leftover("young", 20*time.Second, ours), leftover("other", time.Hour, map[string]string{"x": "y"})}})
	if p := env.probeDNS(context.Background()); p.RC == nil {
		t.Fatalf("probe = %+v", p)
	}
	var rm []string
	for _, c := range node.cmds {
		if _, after, ok := strings.Cut(c, " docker rm -f "); ok {
			rm = append(rm, after)
		}
	}
	if !slices.Equal(rm, []string{"old1 old2"}) {
		t.Fatalf("removed %q, want the two old ones only (commands %q)", rm, node.cmds)
	}

	// The run times out: its container is removed with a context that is
	// still alive.
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	env, node, _ = dnsEnv(t, dnsCase{node: dnsNode{images: "alpine:3.20\n", runErr: context.DeadlineExceeded}, live: ptr(true)})
	if p := env.probeDNS(ctx); p.Skipped == "" {
		t.Fatalf("probe = %+v", p)
	}
	var name string
	for _, c := range node.cmds {
		if _, after, ok := strings.Cut(c, " docker run --rm --name "); ok {
			name, _, _ = strings.Cut(after, " ")
		}
	}
	if name == "" || !strings.HasSuffix(node.cmds[len(node.cmds)-1], " docker rm -f "+name) {
		t.Fatalf("no docker rm -f %q after the failed run: %q", name, node.cmds)
	}
	if len(node.deadRm) > 0 {
		t.Fatalf("removed with a context already done: %q", node.deadRm)
	}
}

