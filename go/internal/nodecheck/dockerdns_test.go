func TestContainerDNSRealNode(t *testing.T) {
	builder := build.BuilderPrefix + "-p1-2c-4g"
	worker := "buildx_buildkit_" + builder + "0"
	r, node, etc := runDNS(t, dnsCase{
		daemonJSON: `{"dns": ["", ""], "live-restore": false}`,
		dockerd:    "/usr/bin/dockerd -H fd:// --containerd=/run/containerd/containerd.sock",
		node:       dnsNode{images: "ghcr.io/pelican-eggs/yolks:java_21\nalpine:3.20\nmoby/buildkit:buildx-stable-1\n", resolv: realNodeResolvConf},
		workers:    map[string]string{worker: realNodeResolvConf},
		live:       ptr(false),
		wings:      true,
	})
	file := filepath.Join(etc, "docker", "daemon.json")
	t.Logf("%v\n  detail: %s\n  hint: %s", r.GetStatus(), r.GetDetail(), r.GetFixHint())
	if r.GetStatus() != agentv1.NodeCheckStatus_NODE_CHECK_STATUS_FAIL {
		t.Fatalf("status = %v %q", r.GetStatus(), r.GetDetail())
	}
	for _, want := range []string{
		"containers get no DNS server they can use",
		`a test container on Docker's default bridge (moby/buildkit:buildx-stable-1) gets "invalid IP", "invalid IP"`,
		`"dns": ["", ""] in ` + file,
		`"", "" are not IP addresses`,
		"builds cannot pull images", "apps cannot look up names outside this server",
	} {
		if !strings.Contains(r.GetDetail(), want) {
			t.Errorf("detail lacks %q:\n%s", want, r.GetDetail())
		}
	}
	for _, want := range []string{
		`Put IP addresses in ` + file + ` ("dns": ["1.1.1.1", "8.8.4.4"]) or remove its "dns" key`,
		"`dockerd --validate --config-file " + file + "`",
		"`systemctl restart docker`",
		"Live-restore is off, so the restart stops every container on this server, Wings' game servers included",
		`add "live-restore": true to ` + file + " and run `systemctl reload docker`",
		"`docker restart " + worker + "`",
		"docker buildx rm " + builder + "`",
		"the next build makes a new one",
		// Live-restore keeps containers running, and each keeps the old
		// servers through Docker's restart.
		"A container that keeps running through the restart keeps its old servers until it is restarted itself (an app with Restart on its page in the panel, a Wings game server from Wings' panel)",
	} {
		if !strings.Contains(r.GetFixHint(), want) {
			t.Errorf("hint lacks %q:\n%s", want, r.GetFixHint())
		}
	}
	if strings.Contains(r.GetFixHint(), "--dns flags") {
		t.Errorf("hint about dockerd flags without any:\n%s", r.GetFixHint())
	}
	// It never pulls: the run says --pull never, and no pull ran. The test
	// container has a name and a label to find it by.
	var ran bool
	runCmd := regexp.MustCompile(`docker run --rm --name seylo-dnscheck-[0-9a-f]{8} --pull never --network bridge --label seylo\.dnscheck=true --label traefik\.enable=false --entrypoint cat moby/buildkit:buildx-stable-1 /etc/resolv\.conf$`)
	for _, c := range node.cmds {
		if strings.Contains(c, "docker run ") {
			ran = true
			if !runCmd.MatchString(c) {
				t.Errorf("test container command %q", c)
			}
		}
		if strings.Contains(c, "docker pull") || strings.Contains(c, "docker image pull") {
			t.Errorf("pulled: %q", c)
		}
	}
	if !ran {
		t.Errorf("no test container ran: %q", node.cmds)
	}
}

