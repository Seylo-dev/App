// realNodeResolvConf is what `docker run --rm alpine:3.20 cat
// /etc/resolv.conf` printed on a Pelican/Wings node whose builds all
// failed: Docker's "dns" setting (daemon.json or dockerd --dns) had two
// entries that are not addresses.
const realNodeResolvConf = `# Generated by Docker Engine.
# This file can be edited; Docker Engine will not make further changes once it
# has been modified.

nameserver invalid IP
nameserver invalid IP
search .

# Based on host file: '/run/systemd/resolve/resolv.conf' (legacy)
# Overrides: [nameservers]
`

// hostResolvConf is a container's file without a "dns" setting.
const hostResolvConf = `# Generated by Docker Engine.
# This file can be edited; Docker Engine will not make further changes once it
# has been modified.

nameserver 1.1.1.1
nameserver 8.8.4.4
search .

# Based on host file: '/run/systemd/resolve/resolv.conf' (legacy)
`

// projectResolvConf is the file of a container on a project network:
// Docker's embedded DNS, which forwards to ext (Docker's ExtServers note,
// "[1.1.1.1 host(127.0.0.53)]").
func projectResolvConf(ext string, override bool) string {
	s := "# Generated by Docker Engine.\n\nnameserver 127.0.0.11\noptions ndots:0\n\n# Based on host file: '/run/systemd/resolve/resolv.conf' (internal resolver)\n# ExtServers: " + ext + "\n"
	if override {
		s += "# Overrides: [nameservers]\n"
	}
	return s + "# Option ndots from: internal\n"
}

func overrideResolvConf(servers ...string) string {
	var b strings.Builder
	b.WriteString("# Generated by Docker Engine.\n\n")
	for _, s := range servers {
		b.WriteString("nameserver " + s + "\n")
	}
	b.WriteString("\n# Based on host file: '/run/systemd/resolve/resolv.conf' (legacy)\n# Overrides: [nameservers]\n")
	return b.String()
}

