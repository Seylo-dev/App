// dnsNode plays the docker CLI and systemctl for the check.
type dnsNode struct {
	images    string // docker image ls
	resolv    string // the test container's /etc/resolv.conf
	runErr    error  // docker run's error
	systemctl string // systemctl show's ExecStart; "" fails
	mainPID   string // systemctl show's MainPID; "" fails
	cmds      []string
	// deadRm are docker rm commands run with a context already done.
	deadRm []string
}

func (n *dnsNode) run(ctx context.Context, w io.Writer, name string, args ...string) error {
	cmd := name + " " + strings.Join(args, " ")
	n.cmds = append(n.cmds, cmd)
	if name == "systemctl" {
		out := n.systemctl
		if slices.Contains(args, "--property=MainPID") {
			out = n.mainPID
		}
		if out == "" {
			return errors.New("no systemd here")
		}
		_, _ = io.WriteString(w, out)
		return nil
	}
	if name != "env" || len(args) < 3 || !strings.HasPrefix(args[0], "DOCKER_CONFIG=") || args[2] != "docker" {
		return fmt.Errorf("unexpected command %s", cmd)
	}
	switch docker := strings.Join(args[3:], " "); {
	case docker == "image ls --format {{.Repository}}:{{.Tag}}":
		_, _ = io.WriteString(w, n.images)
	case strings.HasPrefix(docker, "run "):
		if n.runErr != nil {
			return n.runErr
		}
		_, _ = io.WriteString(w, n.resolv)
	case strings.HasPrefix(docker, "rm -f "):
		if ctx.Err() != nil {
			n.deadRm = append(n.deadRm, docker)
		}
	default:
		return fmt.Errorf("unexpected docker %s", docker)
	}
	return nil
}

// dnsContainer is a running container of ours on the fake node.
type dnsContainer struct {
	name    string
	resolv  string
	network string            // HostConfig.NetworkMode; "" for a project network
	labels  map[string]string // nil: a service instance's
}

type dnsCase struct {
	daemonJSON string // etc/docker/daemon.json; "" for none
	dockerd    string // dockerd's command line, spaces between arguments; "" for no process
	files      map[string]string
	links      map[string]string // symlinks under the fake root, path -> target
	node       dnsNode
	workers    map[string]string // build worker container name -> its resolv.conf
	containers []dnsContainer
	// others are more containers in Docker's list, without a resolv.conf.
	others []DockerContainer
	live   *bool
	wings  bool
}

// runDNS runs the check on a fake node.
func runDNS(t *testing.T, tc dnsCase) (*agentv1.NodeCheckResult, *dnsNode, string) {
	t.Helper()
	env, node, etc := dnsEnv(t, tc)
	r := Run(context.Background(), []Check{check{"docker.dns", containerDNSTitle, env.containerDNS}})[0]
	return r, node, etc
}

func dnsEnv(t *testing.T, tc dnsCase) (*Env, *dnsNode, string) {
	t.Helper()
	files := map[string]string{}
	maps.Copy(files, tc.files)
	if tc.daemonJSON != "" {
		files["etc/docker/daemon.json"] = tc.daemonJSON
	}
	if tc.dockerd != "" {
		files["proc/812/comm"] = "dockerd\n"
		files["proc/812/cmdline"] = strings.ReplaceAll(tc.dockerd, " ", "\x00") + "\x00"
	}
	proc, sys, etc := machine(t, files)
	root := filepath.Dir(proc)
	for path, target := range tc.links {
		full := filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(target, full); err != nil {
			t.Fatal(err)
		}
	}
	rootDir := t.TempDir()
	info := &DockerInfo{ServerVersion: "29.1.0", DockerRootDir: rootDir}
	if tc.live != nil {
		info.LiveRestoreEnabled = *tc.live
	}
	var containers []DockerContainer
	add := func(i int, c DockerContainer, resolv string) {
		c.ID = fmt.Sprintf("%064x", i)
		c.State = "running"
		containers = append(containers, c)
		if err := os.MkdirAll(filepath.Join(rootDir, "containers", c.ID), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(rootDir, "containers", c.ID, "resolv.conf"), []byte(resolv), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	i := 0
	for name, resolv := range tc.workers {
		i++
		c := DockerContainer{Names: []string{"/" + name}}
		c.HostConfig.NetworkMode = "bridge"
		add(i, c, resolv)
	}
	for _, own := range tc.containers {
		i++
		labels := own.labels
		if labels == nil {
			labels = docker.InstanceLabels{ServiceID: "svc" + strconv.Itoa(i), ProjectID: "p1", Kind: "app"}.Map()
		}
		c := DockerContainer{Names: []string{"/" + own.name}, Labels: labels}
		c.HostConfig.NetworkMode = cmp.Or(own.network, "seylo-p-p1")
		add(i, c, own.resolv)
	}
	// Other containers the name filter would leave out.
	containers = append(containers, DockerContainer{ID: fmt.Sprintf("%064x", 99), Names: []string{"/seylo-traefik"}, State: "running"})
	containers = append(containers, tc.others...)
	node := tc.node
	data := t.TempDir()
	env := &Env{DataDir: data, ProcDir: proc, SysDir: sys, EtcDir: etc, RunDir: filepath.Join(root, "run"), Run: node.run,
		Docker: fakeDocker{info: info, publishers: containers}}
	if tc.live == nil {
		// Docker's live-restore unknown: Docker did not answer.
		env.Docker = fakeDocker{err: errors.New("no docker")}
	}
	if tc.wings {
		env.Wings = func(context.Context) (*agentv1.WingsInfo, error) { return &agentv1.WingsInfo{Version: "1.11"}, nil }
	}
	env.defaults()
	return env, &node, etc
}

