func TestParseDaemonJSON(t *testing.T) {
	texts := func(entries []dnsEntry) []string {
		var out []string
		for _, e := range entries {
			out = append(out, e.Text)
		}
		return out
	}
	entries, set, ipv6, err := parseDaemonJSON([]byte(`{"live-restore": true, "dns": ["", null, "1.1.1.1", "1.1.1.1:53", "dns.google", 53, "2606:4700:4700::1111"]}`))
	if err != nil || !set || ipv6 {
		t.Fatalf("set %v ipv6 %v err %v", set, ipv6, err)
	}
	if want := []string{`""`, "null", "1.1.1.1", `"1.1.1.1:53"`, `"dns.google"`, "53", "2606:4700:4700::1111"}; !slices.Equal(texts(entries), want) {
		t.Fatalf("entries %q, want %q", texts(entries), want)
	}
	kinds := []nsKind{nsInvalid, nsInvalid, nsUsable, nsInvalid, nsInvalid, nsInvalid, nsUsable}
	for i, e := range entries {
		if e.Kind != kinds[i] {
			t.Errorf("%s: kind %v, want %v", e.Text, e.Kind, kinds[i])
		}
	}
	if entries, set, _, _ := parseDaemonJSON([]byte(`{"dns": "1.1.1.1"}`)); !set || len(entries) != 1 || entries[0].Kind != nsInvalid {
		t.Fatalf("a string instead of a list = %v %+v", set, entries)
	}
	if _, set, ipv6, err := parseDaemonJSON([]byte(`{"ipv6": true}`)); set || !ipv6 || err != nil {
		t.Fatalf("no dns, ipv6 = %v %v %v", set, ipv6, err)
	}
	if _, _, _, err := parseDaemonJSON([]byte(`{"dns": ["1.1.1.1",]}`)); err == nil {
		t.Fatal("a broken file parsed")
	}
}

