func TestParseResolvConf(t *testing.T) {
	rc := parseResolvConf(realNodeResolvConf)
	if !slices.Equal(rc.Servers, []string{"invalid IP", "invalid IP"}) || !rc.Override || rc.HostFile != "/run/systemd/resolve/resolv.conf" {
		t.Fatalf("the real node's file = %+v", rc)
	}
	if judgeServers(rc.Servers, false) != dnsNone {
		t.Fatal("the real node's file has usable servers")
	}
	rc = parseResolvConf(hostResolvConf)
	if !slices.Equal(rc.Servers, []string{"1.1.1.1", "8.8.4.4"}) || rc.Override {
		t.Fatalf("host servers = %+v", rc)
	}
	rc = parseResolvConf("search example.com\noptions ndots:0\n# nameserver 1.1.1.1\n; nameserver 8.8.8.8\n")
	if len(rc.Servers) != 0 {
		t.Fatalf("comments read as servers: %+v", rc)
	}
	rc = parseResolvConf("nameserver\t2001:4860:4860::8888\nnameserver\n# Overrides: [search options]\n")
	if !slices.Equal(rc.Servers, []string{"2001:4860:4860::8888", ""}) || rc.Override {
		t.Fatalf("tabs, an empty line and other overrides = %+v", rc)
	}
}

