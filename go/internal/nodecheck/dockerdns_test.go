// Nothing to go on (no dockerd visible, no systemd, daemon.json
// unreadable, no image): a warning, never a failure.
func TestContainerDNSUnknown(t *testing.T) {
	r, _, _ := runDNS(t, dnsCase{daemonJSON: "{}", node: dnsNode{}, live: ptr(true)})
	if r.GetStatus() != agentv1.NodeCheckStatus_NODE_CHECK_STATUS_PASS {
		t.Fatalf("an empty readable daemon.json = %v %q", r.GetStatus(), r.GetDetail())
	}
	files := map[string]string{"etc/docker/daemon.json/x": "a folder where the file should be"}
	proc, sys, etc := machine(t, files)
	node := &dnsNode{}
	env := Env{DataDir: t.TempDir(), ProcDir: proc, SysDir: sys, EtcDir: etc, Run: node.run, Docker: fakeDocker{err: errors.New("no docker")}}
	env.defaults()
	r = env.containerDNS(context.Background())
	if r.GetStatus() != agentv1.NodeCheckStatus_NODE_CHECK_STATUS_WARN || !strings.Contains(r.GetDetail(), "could not tell which DNS servers Docker gives containers") ||
		!strings.Contains(r.GetDetail(), "dockerd's command line") || !strings.Contains(r.GetDetail(), "daemon.json") || r.GetFixHint() == "" {
		t.Fatalf("nothing known = %v %q (hint %q)", r.GetStatus(), r.GetDetail(), r.GetFixHint())
	}
	for _, c := range node.cmds {
		if strings.Contains(c, "docker run") {
			t.Fatalf("a test container ran without an image: %q", c)
		}
	}
}

